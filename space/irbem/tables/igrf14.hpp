/**
 * @file igrf14.hpp
 * @brief The IAGA-published IGRF-14 Gauss coefficients, as compile-time data.
 *
 * Generated, never hand-typed. The source is the IAGA V-MOD working group's own release file
 *
 *     https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt
 *
 * retrieved 2026-08-28, SHA-256 `8f8d88403028fc4ee92c4f38d97b46e0a87e2cfc496045b43c9e26c1d6b0903c`.
 * Every literal below is the published decimal text verbatim, so it round-trips to exactly the
 * `double` the publisher's own value denotes; nothing was rescaled, rounded or re-derived. The
 * model is described in Alken et al., *International Geomagnetic Reference Field: the fourteenth
 * generation*, Earth Planets Space (2025), and the file header itself states the normalisation:
 * "Schmidt semi-normalised spherical harmonic coefficients, degree n=1,13, in units nanoTesla".
 *
 * Why a generated header rather than a data file read at run time: `space.irbem` has no data
 * directory, no file I/O and no start-up cost. IRBEM reads `igrf_coef` tables off disk on first
 * use, which is a failure mode (a missing or truncated file) and a load-order hazard that simply
 * does not exist if the numbers are in the binary. It also lets @ref cheatah::space::irbem::Igrf
 * interpolate to a fixed epoch at compile time.
 *
 * Layout: one flat slot per (degree n, order m) pair, at the triangular index
 * `n*(n+1)/2 + m`, for `n = 0..13`. Slot 0 (n=0) and every `h` slot with `m = 0` are structurally
 * absent from the model and hold exactly `0.0`, so the field kernel needs no special case for
 * them. Orders above degree 8 have no published secular variation and hold `0.0` likewise.
 *
 * @note The 26 tabulated epochs are 1900.0 to 2025.0 in 5-year steps. 1900-2020 are *definitive*
 *       (DGRF) and will not change; 2025.0 is the provisional IGRF main field, and
 *       @ref igrf14_g_sv / @ref igrf14_h_sv are the predicted 2025-2030 secular variation in
 *       nT/year, which is how the model is evaluated past its last tabulated epoch.
 *
 * *Regenerate with:* `curl -sSLO https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt`
 * then the awk transcription described above; the file is data, so a regeneration that changes
 * any number means IAGA published a revision, not that this header drifted.
 */

